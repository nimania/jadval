const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const {puzzle,bank,report}=require('./test_quality_gate.cjs');
const window={},document={readyState:'loading',addEventListener(){}};
const context={window,document,Date,Math,Map,Set,crypto:require('node:crypto').webcrypto};
for(const file of ['sparse-generator.js','quality-gate.js','publish.js'])
 vm.runInNewContext(fs.readFileSync(file,'utf8'),context,{filename:file});
const api=window.JadvalSparse,make=window.JadvalPublish.preparedPuzzle;
const valid={puzzle,mask:puzzle.grid.map(row=>row.map(ch=>!ch))};
assert(api.validateWithBank(valid,bank),'Synthetic 15x15 fixture must pass independent bank matching');
const checks=Object.fromEntries(['words','clues','uniqueness','experience','geometry','sources','rights'].map(k=>[k,true]));
const ratings={words:10,clues:10,uniqueness:10,experience:5,geometry:5};
const review=window.JadvalQuality.score(report,ratings,checks,'ویراستار آزمون');
assert.equal(review.ready,true);
const publication=make(valid,bank,'  جدول   شماره ۱  ',review);
assert.equal(publication.title,'جدول شماره ۱');
assert.equal(publication.editorApproved,false,'A fresh draft must never be pre-approved');
assert.deepEqual(Object.keys(publication.puzzle).sort(),['clues','grid','meta','version']);
assert.deepEqual(Object.keys(publication.puzzle.meta).sort(),['direction','language','method','size','status','title']);
assert.equal(publication.puzzle.meta.status,'published');
assert(!JSON.stringify(publication).includes('synthetic-test-only'));
assert(!JSON.stringify(publication).includes('private archive'));
assert(!JSON.stringify(publication).includes('bank-'));
assert.throws(()=>make(valid,bank,'جدول'),/امتیاز/);
assert.throws(()=>make(valid,bank,'جدول',{ready:true,score:89,technical:60}),/امتیاز/);
assert.throws(()=>make(valid,bank.map(row=>({...row,reviewed:0})),'جدول',review),/دروازهٔ کیفیت/);
const sample={...valid,sample:true};
assert.throws(()=>make(sample,bank,'جدول',review),/نمونهٔ آزمایشی/);
assert.throws(()=>make(valid,bank,' ' ,review),/عنوان/);
const invalid=JSON.parse(JSON.stringify(valid));
invalid.puzzle.clues.horizontal['1'][0]='پرسش ساختگی';
assert.throws(()=>make(invalid,bank,'جدول',review),/تطابق/);
const noSym=JSON.parse(JSON.stringify(valid));
noSym.puzzle.grid[0][0]='ا';
assert.throws(()=>make(noSym,bank,'جدول',review),/تطابق|دروازهٔ کیفیت/);
console.log('Publication rejects unreviewed, low-score, sample, invalid and incomplete crosswords; only exact public shape leaves client.');
